import cadquery as cq

def build_model():
    # 侧视轮廓 (XZ平面)，单一线条闭合，确保挤出后为单一水密实体
    pts = [
        (0, -55),    # 底座后下
        (100, -55),  # 底座前下
        (100, -45),  # 底座前上
        (30, -45),   # 底座内前
        (30, -35),   # 底部挡边顶 (高10mm，兼容8-12mm手机)
        (25, -35),   # 底部挡边内顶
        (25, -45),   # 底部挡边内底
        (15, -45),   # 背板前底
        (60, 52),    # 背板前顶 (dx=45, dz=97 -> 倾角约65.1°)
        (62, 52),    # 顶部挡边外顶
        (62, 50.5),  # 顶部挡边外底 (高1.5mm)
        (60, 50.5),  # 顶部挡边内底
        (55, 50.5),  # 顶部挡边内顶过渡
        (10, -42),   # 背板后顶 (厚度约8mm)
        (10, -55),   # 背板后底
        (0, -55),    # 闭合
    ]
    # 拉伸主体 (Y方向宽80mm，居中)
    main = cq.Workplane("XZ").polyline(pts).close().extrude(80).translate((0, -40, 0))

    # 边缘倒角 (仅处理Y向边，避免内部拓扑错误，满足0.5mm防割手要求)
    main = main.edges("|Y").chamfer(0.5)

    # 背板与底座交接处添加R3圆角 (消除应力集中，提升网格质量)
    try:
        main = main.edges("<X").fillet(3.0)
    except Exception:
        pass

    return main

MODEL = build_model()